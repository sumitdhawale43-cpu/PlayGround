const AMBER = '#ffb84d'
const CYAN = '#4de8ff'
const MINT = '#5dffa8'
const ROSE = '#ff6f9f'
const VIOLET = '#b38cff'
const LIME = '#d7ff5f'

function led(id, x, y, color = AMBER) {
  return { id, type: 'led', x, y, color }
}

function sw(id, x, y, initial = false) {
  return { id, type: 'switch', x, y, initial }
}

function gate(id, type, x, y) {
  return { id, type, x, y }
}

function battery(id, x, y) {
  return { id, type: 'battery', x, y }
}

function w(a, b) {
  return { a, b }
}

